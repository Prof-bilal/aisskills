import assert from 'node:assert/strict';
import {mkdtemp,readdir,mkdir,writeFile,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {Client} from '../packages/cli/node_modules/@modelcontextprotocol/sdk/dist/esm/client/index.js';
import {StdioClientTransport} from '../packages/cli/node_modules/@modelcontextprotocol/sdk/dist/esm/client/stdio.js';
const exec=promisify(execFile);
const release=resolve(process.argv[2]??'release');
const archives=(await readdir(release)).filter(f=>f.endsWith('.tgz')&&!f.startsWith('aiskills-workspace-')).map(f=>join(release,f));
assert.equal(archives.length,4,'Exactly four release archives required');
const root=await mkdtemp(join(tmpdir(),'aiskills-release-smoke-'));
console.log(`Clean installation: ${root}`);
await exec('npm',['install','--prefix',root,'--no-audit','--no-fund',...(process.env.AI_SKILLS_SMOKE_ONLINE?[]:['--offline']),...archives],{timeout:180000,maxBuffer:2*1024*1024});
const project=join(root,'project');const source=join(root,'fixture');await mkdir(project);await mkdir(source);
const env={...process.env,AI_SKILLS_HOME:join(root,'state')};
const cli=join(root,'node_modules/@prof-bilal/aiskills/dist/index.js');
const run=async(args)=>(await exec(process.execPath,[cli,...args],{cwd:project,env,timeout:15000,maxBuffer:1024*1024})).stdout;
assert.match(await run(['--help']),/session/);assert.match(await run(['--version']),/\d+\.\d+\.\d+/);
await writeFile(join(source,'SKILL.md'),'---\nname: release-widgets\ndescription: Review widgets carefully\n---\nRelease instruction sentinel.');
await run(['add',source,'--yes']);await run(['skills','enable','release-widgets']);
assert.match(await run(['plan','review widgets']),/release-widgets/);
const lock=JSON.parse(await readFile(join(project,'aiskills.lock'),'utf8'));assert.equal(lock.schema_version,2);
const client=new Client({name:'release-smoke',version:'1'});
const transport=new StdioClientTransport({command:process.execPath,args:[cli,'mcp'],cwd:project,env});
try {await client.connect(transport);const discovered=await client.callTool({name:'discover_capabilities',arguments:{task:'review widgets'}});assert.deepEqual(JSON.parse(discovered.content[0].text).selectedPackages,['release-widgets']);const loaded=await client.callTool({name:'load_skill',arguments:{id:'release-widgets'}});assert.match(loaded.content[0].text,/Release instruction sentinel/);} finally {await client.close();}
await run(['skills','disable','release-widgets']);await run(['skills','remove','release-widgets']);
console.log('PASS: packed CLI, SQLite imports, project lockfile, routing, MCP discovery/load, disable and removal');
console.log('Artifacts retained for inspection; no packages were published.');
